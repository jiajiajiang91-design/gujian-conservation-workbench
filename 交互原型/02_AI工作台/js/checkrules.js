/* 出图检查。规则程序按当前数据实时算，不是预先写好的几条。
   改一个构件、删一条实测，检查结果就跟着变。
   分两类：能自动修的（结果唯一、可再次验证）和必须人决定的。 */
window.CheckRules = (function () {

  function 重叠(a, b) {
    return !(a[2] <= b[0] || b[2] <= a[0] || a[3] <= b[1] || b[3] <= a[1]);
  }
  function 面积(f) { return (f[2] - f[0]) * (f[3] - f[1]); }

  function run(S) {
    const out = [];
    let n = 0;
    const add = (类型, 严重, 标题, 说明, 位置, 选项) => {
      out.push({ id: "rc" + (++n), 类型, 严重, 标题, 说明, 位置,
        处理: 严重 === "自动修复" ? "auto" : "pending", 选项: 选项 || null });
    };

    // ===== 自动修复类：结果唯一，可再次验证 =====

    // 1. 图签比例字段
    if (S.任务卡.比例 && S.任务卡.比例.值) {
      add("规范", "自动修复", "图签比例字段已填",
        "图签比例字段原为空，已按任务卡填入 " + S.任务卡.比例.值 + "。", "图签");
    }

    // 2. 标注碰撞：同类构件位置框重叠面积过大时标注会压线
    const 主体 = S.构件.filter(p => p.类别 !== "环境陈设" && p.类别 !== "彩画");
    let 碰撞 = 0, 碰撞例 = "";
    for (let i = 0; i < 主体.length; i++) {
      for (let j = i + 1; j < 主体.length; j++) {
        const a = 主体[i], b = 主体[j];
        if (!重叠(a.框, b.框)) continue;
        const 小 = Math.min(面积(a.框), 面积(b.框));
        const ox = Math.min(a.框[2], b.框[2]) - Math.max(a.框[0], b.框[0]);
        const oy = Math.min(a.框[3], b.框[3]) - Math.max(a.框[1], b.框[1]);
        if (小 > 0 && (ox * oy) / 小 > 0.55) {
          碰撞++;
          if (!碰撞例) 碰撞例 = a.编号 + " 与 " + b.编号;
        }
      }
    }
    if (碰撞) {
      add("规范", "自动修复", "标注位置已避让",
        "检测到 " + 碰撞 + " 处构件标注区域重叠（例如 " + 碰撞例 + "），已把重叠处标注移至构件外侧。", "图面");
    }

    // ===== 需要人决定类 =====

    // 3. 推测值进图
    const 推测 = S.构件.filter(p => (p.状态 === "ai" || p.状态 === "demo") && (p.尺寸 || "").trim());
    if (推测.length) {
      add("几何", "需决定", 推测.length + " 项构件尺寸无实测依据",
        "这些尺寸由照片比例估算，没有实测支持。按任务书要求，无实测依据的尺寸不得作为正式成果尺寸标注。" +
        "涉及：" + 推测.slice(0, 5).map(p => p.编号).join("、") + (推测.length > 5 ? " 等" : "") + "。",
        "全图",
        ["全部加括注标为估算值", "只保留有实测支持的尺寸，其余不标", "安排补测后重新出图"]);
    }

    // 4. 不可见部位
    const 不可见 = S.构件.filter(p => p.状态 === "unknown");
    if (不可见.length) {
      add("规范", "需决定", 不可见.length + " 处为不可见部位",
        "被遮挡或无法确认的部位不能按推测绘制。规范要求现状图只反映可确认的内容。",
        不可见.map(p => p.编号).join("、"),
        ["在图上标注为不可见部位并加说明", "安排补拍后重画", "暂时留白并在交付说明中写明"]);
    }

    // 5. 未处理的存疑项
    const 存疑 = S.存疑.filter(q => !q.已解决);
    if (存疑.length) {
      add("几何", "需决定", "还有 " + 存疑.length + " 项存疑未判定",
        "存疑构件的形制未确定，图上只能按当前判断绘制。涉及：" +
        存疑.map(q => q.标题).join("；") + "。",
        存疑.map(q => q.构件).filter(Boolean).join("、") || "构件清单",
        ["按当前判断出图，在图上标注待复核", "先处理存疑项再出图"]);
    }

    // 6. 材料无检测依据
    const 外观判断 = S.现状.filter(c => (c.状态 === "ai" || c.状态 === "demo") && /材质|瓦作|彩画/.test(c.项目 + c.内容));
    if (外观判断.length) {
      add("规范", "需决定", 外观判断.length + " 项材料只有外观判断",
        "材料信息来自照片外观判断，没有取样检测依据。按规范应在材料表中标明判断方式。",
        "材料表",
        ["全部标注为外观判断", "安排取样检测", "在材料表中留空并说明"]);
    }

    // 7. 缺尺寸的构件
    const 无尺寸 = S.构件.filter(p => p.类别 !== "环境陈设" && p.类别 !== "彩画" && !(p.尺寸 || "").trim());
    if (无尺寸.length) {
      add("几何", "需决定", 无尺寸.length + " 项构件没有任何尺寸",
        "这些构件在图上只能画出轮廓，不能标注尺寸：" + 无尺寸.map(p => p.编号 + " " + p.名称).join("、") + "。",
        无尺寸.map(p => p.编号).join("、"),
        ["按图面比例补估算值", "保持无尺寸，仅画轮廓"]);
    }

    // 8. 实测数据本身的矛盾，复用同一套核对规则
    const 尺寸矛盾 = window.DatumCheck.run(S.实测);
    尺寸矛盾.forEach(c => {
      add("几何", "需决定", "实测数据矛盾：" + c.标题, c.算式 + "。" + c.说明, "实测基准",
        ["按通面阔建立基准，图上标注差值待复核", "暂停出图，等现场复核"]);
    });

    // 9. 责任人未指定
    const 缺人 = S.人员.filter(p => !p.姓名);
    if (缺人.length) {
      add("规范", "需决定", 缺人.length + " 个角色未指定",
        "未指定" + 缺人.map(p => p.角色).join("、") + "。图签的审核与签发栏无法填写，也不能进入签发环节。",
        "图签",
        ["现在去任务卡指定", "先出草图，签发前再定"]);
    }

    return out;
  }

  return { run };
})();
